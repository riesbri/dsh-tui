/**
 * The bilingual documentation gate.
 *
 * Every in-scope document is maintained as a PAIR: the English `foo.md`, the
 * Simplified Chinese `foo.zh.md`, and a consistency record `foo.i18n.yaml`
 * holding the git blob hash of each side as of the last time the two were
 * confirmed to say the same thing. Editing either side without re-confirming
 * the pair turns this red.
 *
 * This exists because the alternative already failed once. An earlier set of
 * translations was authored, never merged, and silently drifted ~530 lines
 * behind English until nobody could tell which parts were still true. A gate
 * that goes red the moment one side moves is the difference between a stale
 * paragraph and a lost branch.
 *
 * Blob hashes rather than commit hashes, so the record is computable for files
 * edited in the same PR and consistency is a pure content comparison. The hash
 * is computed here rather than shelled out to `git hash-object`, so an
 * uncommitted working-tree file is checkable without touching the object
 * database and the whole corpus costs one pass instead of one process per file.
 *
 * The check is deliberately narrower than upstream Harness's: no merge driver,
 * no snapshot refs, no briefing generator. What it does share is the honest
 * limit — a green gate means the pair was confirmed consistent at these exact
 * contents, NOT that the confirmation was sound. It compares hashes and
 * Markdown structure; whether the two sides actually say the same thing, in the
 * right terminology, is the reviewer's half of the contract.
 *
 * Terminology is upstream's `docs/i18n/terminology.md`; this file's local scope
 * and glossary decisions are recorded in `docs/i18n.md`.
 */

import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Repository root, resolved from this file rather than the caller's cwd. */
export const ROOT = fileURLToPath(new URL('..', import.meta.url))

/**
 * Directories searched for in-scope documents. A bare filename is one document;
 * a directory contributes every `.md` in it. Kept explicit rather than a
 * recursive walk, so adding a documentation root is a visible decision.
 */
const SCOPE = ['README.md', 'ROADMAP.md', 'CONTRIBUTING.md', 'SECURITY.md', 'docs']

/**
 * Documents that are never paired, and for which a `.zh.md` or `.i18n.yaml` is
 * itself an error.
 *
 * `AGENTS.md` is agent instructions, maintained in English only exactly as
 * upstream keeps its own. `CHANGELOG.md` is generated by Changesets, so a
 * translated copy would be overwritten by the next release. `docs/i18n.md`
 * documents the pairing rules themselves and quotes both languages by
 * construction.
 */
export const EXCLUDED = new Set(['AGENTS.md', 'CHANGELOG.md', 'docs/i18n.md'])

/**
 * In-scope documents that do not have a Chinese counterpart YET.
 *
 * A pending document is reported on every run and does not fail the gate; a
 * document NOT listed here must be a complete pair. The list exists so the
 * corpus can be completed one reviewed translation at a time without the gate
 * being either red for weeks or silently narrowed — the difference between a
 * visible backlog and a scope gap nobody remembers. Deleting the last entry is
 * the point; nothing may be added without also saying why in the pull request.
 */
export const PENDING = new Set([
  'README.md',
  'ROADMAP.md',
  'CONTRIBUTING.md',
  'SECURITY.md',
  'docs/architecture.md',
  'docs/comparison.md',
  'docs/design.md',
  'docs/install.md',
  'docs/provider-acceptance.md',
  'docs/roadmap.md',
  'docs/usage.md',
])

/** The Chinese side's suffix, and the marker that identifies one. */
const ZH_SUFFIX = '.zh.md'

/**
 * Either side's switcher, in full. Matched rather than substring-searched: the
 * English form is `English | [中文](foo.zh.md)`, where the pipe and the
 * characters are separated by a bracket, so a naive `includes('| 中文')` misses it
 * and counts the switcher as an ordinary link on one side but not the other.
 */
const SWITCHER_LINE = /^(?:English \| \[中文\]\([^)]+\)|\[English\]\([^)]+\) \| 中文)$/u

/** The switcher the Chinese side must carry immediately after its H1. */
const ZH_SWITCHER = enPath => `[English](${basename(enPath)}) | 中文`

/** The switcher the English side must carry immediately after its H1. */
const EN_SWITCHER = zhPath => `English | [中文](${basename(zhPath)})`

/**
 * The git blob hash of a string: sha1 over `blob <byteLength>\0<content>`.
 *
 * Byte length, not character count — a Chinese document is roughly three bytes
 * per character, so a `.length` here would disagree with git on every paired
 * file and agree on none of them.
 * @param text - the file contents.
 * @returns the 40-character hex blob hash.
 */
export function blobHash(text) {
  const body = Buffer.from(text, 'utf8')
  return createHash('sha1')
    .update(`blob ${body.length}\0`)
    .update(body)
    .digest('hex')
}

/**
 * Split a document into fenced-code regions and everything else.
 *
 * Every other structural reader depends on this: a `#` inside a shell fence is
 * a comment, a `|` inside one is a pipe, and counting either as structure makes
 * the signature disagree between two files that are in fact identical.
 * @param text - the file contents.
 * @returns the fences in order, and the lines outside any fence.
 */
export function partition(text) {
  const fences = []
  const prose = []
  let open
  for (const line of text.split('\n')) {
    const delimiter = /^\s*(`{3,}|~{3,})(.*)$/u.exec(line)
    if (open === undefined) {
      if (delimiter !== null) {
        open = { marker: delimiter[1][0], length: delimiter[1].length, info: delimiter[2].trim(), body: [] }
        continue
      }
      prose.push(line)
      continue
    }
    // A closing delimiter must use the same character and be at least as long
    // as the opener, so a ```` ``` ```` inside a ```` ```` ```` block stays body.
    const closes = delimiter !== null
      && delimiter[1][0] === open.marker
      && delimiter[1].length >= open.length
      && delimiter[2].trim() === ''
    if (closes) {
      fences.push({ info: open.info, body: open.body.join('\n') })
      open = undefined
      continue
    }
    open.body.push(line)
  }
  if (open !== undefined) fences.push({ info: open.info, body: open.body.join('\n'), unterminated: true })
  return { fences, prose }
}

/**
 * The structural fingerprint two sides of a pair must share.
 *
 * Structure is the part of "they say the same thing" a machine can actually
 * check: a translation that drops a table row, reorders a section, or silently
 * loses a list item is wrong in a way review misses and this catches. Prose
 * length is deliberately NOT part of it — Chinese is denser than English and a
 * faithful translation is routinely shorter.
 * @param text - the file contents.
 * @returns the comparable signature.
 */
export function signature(text) {
  const { fences, prose } = partition(text)
  const headings = []
  const tables = []
  const lists = []
  let table
  let list
  for (const line of prose) {
    const heading = /^(#{1,6})\s+\S/u.exec(line)
    if (heading !== null) {
      headings.push(heading[1].length)
      table = undefined
      list = undefined
      continue
    }
    if (line.trim().startsWith('|')) {
      // The delimiter row (`| --- |`) is chrome, not content: it exists once per
      // table and carries the column count, which is counted from it instead.
      const cells = line.trim().replace(/^\||\|$/gu, '').split('|').length
      const delimiter = /^\s*\|?[\s:|-]+\|[\s:|-]*$/u.test(line) && line.includes('-')
      if (table === undefined) {
        table = { rows: 0, columns: cells }
        tables.push(table)
      }
      if (!delimiter) table.rows += 1
      continue
    }
    table = undefined
    const item = /^(\s*)(?:([-*+])|(\d+)[.)])\s+\S/u.exec(line)
    if (item !== null) {
      const kind = item[2] !== undefined ? 'ul' : 'ol'
      const start = item[3] !== undefined ? Number(item[3]) : undefined
      const depth = item[1].length
      if (list === undefined || list.kind !== kind || list.depth !== depth) {
        list = { kind, depth, start, items: 0 }
        lists.push(list)
      }
      list.items += 1
      continue
    }
    // A blank line continues a list (loose lists are still one list); anything
    // else at column zero ends it.
    if (line.trim() !== '' && !/^\s/u.test(line)) list = undefined
  }
  return {
    headings,
    fences: fences.map(fence => ({ info: fence.info, body: fence.body })),
    tables: tables.map(entry => ({ rows: entry.rows, columns: entry.columns })),
    lists: lists.map(entry => ({ kind: entry.kind, start: entry.start, items: entry.items })),
  }
}

/**
 * Relative Markdown link targets outside fenced code, excluding the language
 * switcher, which is the one link a pair is REQUIRED to differ on.
 * @param text - the file contents.
 * @returns the targets in document order.
 */
export function documentLinks(text) {
  const { prose } = partition(text)
  const targets = []
  for (const line of prose) {
    if (SWITCHER_LINE.test(line.trim())) continue
    for (const match of line.matchAll(/\[[^\]]*\]\(([^)\s]+)\)/gu)) {
      const target = match[1]
      if (/^[a-z][a-z0-9+.-]*:/iu.test(target) || target.startsWith('#')) continue
      targets.push(target)
    }
  }
  return targets
}

/**
 * The `.i18n.yaml` record: two `path: hash` lines and comments.
 *
 * Parsed and written by hand rather than through the `yaml` dependency, because
 * this file must stay runnable with nothing installed — it is the check a
 * contributor reaches for before `pnpm install` finishes.
 * @param text - the record's contents.
 * @returns the recorded hash per filename.
 */
export function parseRecord(text) {
  const recorded = {}
  for (const line of text.split('\n')) {
    const entry = /^([^#\s][^:]*):\s*([0-9a-f]{40})\s*$/u.exec(line)
    if (entry !== null) recorded[entry[1].trim()] = entry[2]
  }
  return recorded
}

/**
 * Render a record, with the instruction for the next person to hit it red.
 * @param pair - the pair being recorded.
 * @param hashes - the confirmed hash per filename.
 * @returns the file contents.
 */
export function renderRecord(pair, hashes) {
  return `# Bilingual-pair consistency record (docs/i18n.md): the git blob hash of each side\n`
    + `# as of the last confirmed-consistent state. Both languages carry equal authority;\n`
    + `# after editing either side, bring the other along and re-record with:\n`
    + `#   pnpm run verify-docs --write ${pair.en}\n`
    + `${basename(pair.en)}: ${hashes[basename(pair.en)]}\n`
    + `${basename(pair.zh)}: ${hashes[basename(pair.zh)]}\n`
}

/**
 * Every in-scope document, as a pair of the three paths it needs.
 * @param root - the repository root to read.
 * @returns the pairs, in a stable order.
 */
export function discoverPairs(root = ROOT) {
  const documents = []
  for (const entry of SCOPE) {
    // A scope entry that is absent contributes nothing. Only an entry that
    // exists AND is a directory expands; anything else is one document, so a
    // missing README is a missing file rather than a phantom pair.
    let stats
    try {
      stats = statSync(join(root, entry))
    } catch {
      continue
    }
    if (!stats.isDirectory()) {
      documents.push(entry)
      continue
    }
    for (const name of readdirSync(join(root, entry)).sort()) {
      if (name.endsWith('.md') && !name.endsWith(ZH_SUFFIX)) documents.push(`${entry}/${name}`)
    }
  }
  return documents
    .filter(document => !EXCLUDED.has(document))
    .map(en => ({
      name: en.replace(/\.md$/u, ''),
      en,
      zh: en.replace(/\.md$/u, ZH_SUFFIX),
      record: en.replace(/\.md$/u, '.i18n.yaml'),
    }))
}

/**
 * Read a file, or undefined when it is not there.
 * @param path - the absolute path.
 * @returns the contents, or undefined.
 */
function read(path) {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return undefined
  }
}

/**
 * The switcher line a side must carry: the first non-blank line after its H1.
 * @param text - the file contents.
 * @returns the line, or undefined when there is no H1 or nothing follows it.
 */
function switcherLine(text) {
  const lines = text.split('\n')
  const heading = lines.findIndex(line => /^#\s+\S/u.test(line))
  if (heading === -1) return undefined
  return lines.slice(heading + 1).find(line => line.trim() !== '')?.trim()
}

/**
 * Check one pair, reporting every problem rather than the first.
 *
 * A partial report would make this a game of whack-a-mole across a nine-document
 * corpus, so the caller gets the whole list for a pair at once.
 * @param pair - the pair to check.
 * @param root - the repository root to read.
 * @returns the state, and the problems found.
 */
export function checkPair(pair, root = ROOT) {
  const en = read(join(root, pair.en))
  const zh = read(join(root, pair.zh))
  const record = read(join(root, pair.record))
  const problems = []

  if (en === undefined) problems.push(`${pair.en} is missing`)
  if (zh === undefined || record === undefined) {
    const absent = [zh === undefined ? pair.zh : undefined, record === undefined ? pair.record : undefined]
      .filter(path => path !== undefined)
      .map(path => `${path} is missing`)
    // A pending document is a known gap, not a regression: it reports, it does
    // not fail. A half-built pair always fails, pending or not — one file
    // without its record is the exact state that produced the drift this gate
    // exists to prevent.
    const started = zh !== undefined || record !== undefined
    if (PENDING.has(pair.en) && !started && problems.length === 0) {
      return { pair, state: 'pending', problems: [], notes: absent }
    }
    return { pair, state: 'missing', problems: [...problems, ...absent] }
  }
  if (en === undefined) return { pair, state: 'missing', problems }
  if (PENDING.has(pair.en)) {
    problems.push(`${pair.en} has a counterpart now; remove it from PENDING in tools/verify-translation-pairing.mjs`)
  }

  const hashes = { [basename(pair.en)]: blobHash(en), [basename(pair.zh)]: blobHash(zh) }
  const recorded = parseRecord(record)
  let stale = false
  for (const [name, hash] of Object.entries(hashes)) {
    if (recorded[name] === undefined) {
      problems.push(`${pair.record} records no hash for ${name}`)
      stale = true
    } else if (recorded[name] !== hash) {
      problems.push(`${name} changed since the pair was confirmed (recorded ${recorded[name].slice(0, 12)}, now ${hash.slice(0, 12)})`)
      stale = true
    }
  }

  const zhSwitcher = ZH_SWITCHER(pair.en)
  if (switcherLine(zh) !== zhSwitcher) {
    problems.push(`${pair.zh} must carry \`${zhSwitcher}\` immediately after its H1`)
  }
  const enSwitcher = EN_SWITCHER(pair.zh)
  if (switcherLine(en) !== enSwitcher) {
    problems.push(`${pair.en} must carry \`${enSwitcher}\` immediately after its H1`)
  }

  problems.push(...compareSignatures(pair, signature(en), signature(zh)))
  problems.push(...compareLinks(pair, documentLinks(en), documentLinks(zh), root))

  return { pair, state: problems.length === 0 ? 'ok' : stale ? 'out-of-sync' : 'invalid', problems, hashes }
}

/**
 * Compare two structural signatures, naming the first divergence of each kind.
 * @param pair - the pair being compared, for message context.
 * @param en - the English signature.
 * @param zh - the Chinese signature.
 * @returns the problems found.
 */
function compareSignatures(pair, en, zh) {
  const problems = []
  if (en.headings.join(',') !== zh.headings.join(',')) {
    problems.push(`${pair.name}: heading structure differs (English ${en.headings.length} headings [${en.headings.join(' ')}], Chinese ${zh.headings.length} [${zh.headings.join(' ')}])`)
  }
  if (en.fences.length !== zh.fences.length) {
    problems.push(`${pair.name}: ${en.fences.length} code fences in English, ${zh.fences.length} in Chinese`)
  } else {
    en.fences.forEach((fence, index) => {
      const other = zh.fences[index]
      if (fence.info !== other.info) problems.push(`${pair.name}: fence ${index + 1} info string differs (\`${fence.info}\` vs \`${other.info}\`)`)
      else if (fence.body !== other.body) problems.push(`${pair.name}: fence ${index + 1} body is not byte-identical; code blocks are verbatim on both sides`)
    })
  }
  if (JSON.stringify(en.tables) !== JSON.stringify(zh.tables)) {
    problems.push(`${pair.name}: table shape differs (English ${JSON.stringify(en.tables)}, Chinese ${JSON.stringify(zh.tables)})`)
  }
  if (JSON.stringify(en.lists) !== JSON.stringify(zh.lists)) {
    problems.push(`${pair.name}: list structure differs (English ${en.lists.length} lists, Chinese ${zh.lists.length})`)
  }
  return problems
}

/**
 * Compare link targets, requiring each side to link within its own locale.
 *
 * An English document links `docs/usage.md`; its Chinese counterpart links
 * `docs/usage.zh.md`. Without this a reader who follows one link out of the
 * Chinese docs never finds their way back in.
 * @param pair - the pair being compared, for message context.
 * @param en - the English targets.
 * @param zh - the Chinese targets.
 * @param root - the repository root, to tell a paired target from any other.
 * @returns the problems found.
 */
function compareLinks(pair, en, zh, root) {
  if (en.length !== zh.length) {
    return [`${pair.name}: ${en.length} document links in English, ${zh.length} in Chinese`]
  }
  const paired = new Set(discoverPairs(root).flatMap(entry => [entry.en, entry.zh]))
  const problems = []
  en.forEach((target, index) => {
    const other = zh[index]
    const resolved = relative(root, resolve(dirname(join(root, pair.en)), target)).split('\\').join('/')
    const expected = paired.has(resolved) ? target.replace(/\.md(?=$|[#?])/u, ZH_SUFFIX) : target
    if (other !== expected) {
      problems.push(`${pair.name}: link ${index + 1} should be \`${expected}\` on the Chinese side, not \`${other}\``)
    }
  })
  return problems
}

/**
 * Check the whole corpus, or the named subset.
 * @param options - the root to read, and which pairs to check.
 * @returns one result per pair, in discovery order.
 */
export function verifyTranslationPairing({ root = ROOT, only } = {}) {
  const pairs = discoverPairs(root)
  const selected = only === undefined || only.length === 0
    ? pairs
    : only.map(name => {
      const stem = name.replace(/\.i18n\.yaml$/u, '').replace(/\.zh\.md$/u, '').replace(/\.md$/u, '')
      const found = pairs.find(pair => pair.name === stem)
      if (found === undefined) throw new Error(`${name} does not name a document in the bilingual scope`)
      return found
    })
  return selected.map(pair => checkPair(pair, root))
}

/**
 * Re-record the named pairs at their current contents.
 *
 * `--write` requires naming the pairs, because the yaml diff IS the reviewable
 * act of confirming that two documents say the same thing. A blanket re-record
 * would let an unreviewed translation through the gate wearing a green check.
 * @param names - the pairs to confirm.
 * @param root - the repository root to write into.
 * @returns the pairs that were re-recorded.
 */
export function writeRecords(names, root = ROOT) {
  if (names.length === 0) throw new Error('--write needs the pairs you confirmed, e.g. --write README.md')
  const written = []
  for (const result of verifyTranslationPairing({ root, only: names })) {
    if (result.hashes === undefined) {
      throw new Error(`cannot record ${result.pair.name}:\n  ${result.problems.join('\n  ')}`)
    }
    writeFileSync(join(root, result.pair.record), renderRecord(result.pair, result.hashes))
    written.push(result.pair.name)
  }
  return written
}

/**
 * Run the gate from the command line.
 * @param argv - arguments after the script name.
 * @param out - where to write the report.
 * @returns the process exit code.
 */
export function main(argv, out = process.stdout) {
  const write = argv.includes('--write')
  const list = argv.includes('--list')
  const names = argv.filter(argument => !argument.startsWith('-'))

  if (write) {
    const written = writeRecords(names)
    out.write(`recorded ${written.length} pair${written.length === 1 ? '' : 's'}: ${written.join(', ')}\n`)
    return 0
  }

  const results = verifyTranslationPairing({ only: names })
  if (list) {
    for (const result of results) out.write(`${result.state.padEnd(11)} ${result.pair.name}\n`)
    return 0
  }

  const pending = results.filter(result => result.state === 'pending')
  const failures = results.filter(result => result.problems.length > 0)
  if (failures.length === 0) {
    const paired = results.length - pending.length
    out.write(`${paired} bilingual pair${paired === 1 ? '' : 's'} consistent\n`)
    if (pending.length > 0) {
      out.write(`${pending.length} document${pending.length === 1 ? '' : 's'} awaiting a Chinese counterpart: ${pending.map(result => result.pair.en).join(', ')}\n`)
    }
    return 0
  }
  for (const failure of failures) {
    out.write(`${failure.pair.name} (${failure.state})\n`)
    for (const problem of failure.problems) out.write(`  ${problem}\n`)
  }
  out.write(`\nBring the counterpart along, then re-record: pnpm run verify-docs --write <pair>\n`)
  return 1
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    process.exit(main(process.argv.slice(2)))
  } catch (error) {
    process.stderr.write(`${error.message}\n`)
    process.exit(1)
  }
}
